#!/usr/bin/env python3
"""Build the desktop UI/language icon sprite.

Source files (kept in the repo, NOT shipped):
  apps/desktop/icon-src/ui/*.png       33 UI icons, originally 64x64 PNG
  apps/desktop/icon-src/language/*.png 17 language icons, originally 64x64 PNG

Derivatives (shipped):
  apps/desktop/public/icons/sprite.webp  all icons resized to 32x32 and
                                        composed into a single WebP sprite
                                        (10 columns); one HTTP request for
                                        every icon on screen.
  apps/desktop/src/components/icon-sprite.ts  name -> cell index map that
                                        Icons.tsx reads; regenerated here so
                                        the sprite order can never drift from
                                        the component.

The 32x32 WebP sprite is a pure format derivative of the original PNGs above;
the artwork itself is unchanged. Asset rights are recorded in
THIRD_PARTY_NOTICES.md.
Re-run after adding/removing/renaming a source icon:

  python scripts/convert-icons.py
"""

from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image

REPO_ROOT = Path(__file__).resolve().parent.parent
DESKTOP = REPO_ROOT / "apps" / "desktop"
SOURCE_DIRS = {
    "UI_ICON": DESKTOP / "icon-src" / "ui",
    "LANGUAGE_ICON": DESKTOP / "icon-src" / "language",
}
SPRITE_PATH = DESKTOP / "public" / "icons" / "sprite.webp"
MAP_PATH = DESKTOP / "src" / "components" / "icon-sprite.ts"
CELL = 32
COLUMNS = 10


def fail(message: str) -> "sys.NoReturn":
    print(f"convert-icons: {message}", file=sys.stderr)
    sys.exit(1)


def load_cells(directory: Path) -> list[tuple[str, Image.Image]]:
    files = sorted(directory.glob("*.png"))
    if not files:
        fail(f"no PNG sources found in {directory}")
    cells = []
    for file in files:
        with Image.open(file) as image:
            if image.size != (64, 64):
                fail(f"{file.name} is {image.size[0]}x{image.size[1]}, expected 64x64")
            cells.append((file.stem, image.convert("RGBA").resize((CELL, CELL), Image.LANCZOS)))
    return cells


def main() -> None:
    groups = {key: load_cells(path) for key, path in SOURCE_DIRS.items()}
    for key, cells in groups.items():
        if len(cells) != len({name for name, _ in cells}):
            fail(f"duplicate icon names in {SOURCE_DIRS[key]}")

    rows = sum((len(cells) + COLUMNS - 1) // COLUMNS for cells in groups.values())
    sprite = Image.new("RGBA", (COLUMNS * CELL, rows * CELL), (0, 0, 0, 0))
    lines = [
        "// Generated by scripts/convert-icons.py from apps/desktop/icon-src",
        "// (original 64x64 PNGs). Do not edit by hand; re-run the script.",
        f"export const SPRITE_URL = \"/icons/sprite.webp\";",
        f"export const SPRITE_COLUMNS = {COLUMNS};",
        f"export const SPRITE_ROWS = {rows};",
        "",
    ]
    offset = 0
    for key, cells in groups.items():
        group_rows = (len(cells) + COLUMNS - 1) // COLUMNS
        lines.append(f"export const {key}_CELLS: Record<string, number> = {{")
        for index, (name, image) in enumerate(cells):
            col = (offset + index) % COLUMNS
            row = (offset + index) // COLUMNS
            sprite.paste(image, (col * CELL, row * CELL))
            lines.append(f"  \"{name}\": {offset + index},")
        lines.append("};")
        lines.append("")
        offset += group_rows * COLUMNS

    SPRITE_PATH.parent.mkdir(parents=True, exist_ok=True)
    sprite.save(SPRITE_PATH, "WEBP", lossless=True, quality=100, method=6)
    MAP_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {SPRITE_PATH.relative_to(REPO_ROOT)} ({SPRITE_PATH.stat().st_size} bytes)")
    print(f"wrote {MAP_PATH.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
